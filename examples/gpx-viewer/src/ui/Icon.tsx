export type IconName = keyof typeof ICONS

const paths = new Map<IconName, string>()

function pathOf(name: IconName) {
  let path = paths.get(name)
  if (path === undefined) {
    path = ''
    ICONS[name].forEach((row, y) => {
      for (const match of row.matchAll(/#+/g)) {
        path += `M${match.index} ${y}h${match[0].length}v1h-${match[0].length}z`
      }
    })
    paths.set(name, path)
  }
  return path
}

export function Icon({
  name,
  cell = 2,
  className,
  label
}: {
  name: IconName
  /** CSS pixels per grid cell */
  cell?: number
  className?: string
  /** accessible name; icons without one are decorative */
  label?: string
}) {
  const rows = ICONS[name]
  const width = rows[0].length
  const height = rows.length
  return (
    <svg
      viewBox={`0 0 ${width} ${height}`}
      width={width * cell}
      height={height * cell}
      shapeRendering='crispEdges'
      fill='currentColor'
      className={className}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      <path d={pathOf(name)} />
    </svg>
  )
}
